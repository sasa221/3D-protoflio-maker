async function requestAuthEmailApi(path, body) {
  const response = await fetch(path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body)
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) {
    const error = new Error(payload.error || 'Authentication email request failed.');
    error.code = payload.code || (response.status === 429 ? 'over_email_send_rate_limit' : 'email_delivery');
    throw error;
  }
  return payload;
}

export async function signUpUser(email, password, displayName = '') {
  const payload = await requestAuthEmailApi('/api/auth/signup', {
    email: email.trim(),
    password,
    displayName
  });
  return {
    user: payload.user || null,
    session: null,
    emailSent: payload.emailSent !== false,
    otpLength: payload.otpLength || null,
    verificationType: payload.verificationType || 'signup'
  };
}

export async function loginUser(email, password) {
  const { data, error } = await supabase.auth.signInWithPassword({
    email: email.trim(),
    password: password
  });

  if (error) throw error;
  return data;
}

export async function logoutUser() {
  const { error } = await supabase.auth.signOut();
  if (error) console.warn('Supabase logout warning:', error.message);

  // Clear memory cache and user storage
  try {
    ScopedStorageService.wipeAllUserCaches();
  } catch (e) {}
}

export async function getAuthSession() {
  const { data, error } = await supabase.auth.getSession();
  if (error || !data?.session) {
    return null;
  }

  const session = data.session;
  // If access token is expired or expires within 10 seconds, attempt legitimate refresh
  const now = Math.floor(Date.now() / 1000);
  if (session.expires_at && session.expires_at <= now + 10) {
    const { data: refreshed, error: refreshErr } = await supabase.auth.refreshSession().catch(() => ({ data: null, error: true }));
    if (refreshErr || !refreshed?.session) {
      await logoutUser();
      return null;
    }
    return refreshed.session;
  }

  return session;
}

