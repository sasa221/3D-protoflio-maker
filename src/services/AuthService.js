export async function requestPasswordReset(email) {
  const { data, error } = await supabase.auth.resetPasswordForEmail(email.trim(), {
    redirectTo: `${window.location.origin}/reset-password`
  });
  if (error) throw error;
  return data;
}

export async function verifyEmailOtp(email, token) {
  if (!email || !token) throw new Error('Email and verification code are required.');

  // Codes generated by the custom Brevo API can be either signup (first
  // message) or magiclink (resend). Supabase also accepts the generic email
  // type for newer projects, so keep all compatible variants here.
  let result = { data: null, error: null };
  for (const type of ['signup', 'magiclink', 'email']) {
    result = await supabase.auth.verifyOtp({
      email: email.trim(),
      token: token.trim(),
      type
    });
    if (!result.error) break;
  }

  if (result.error) throw result.error;

  if (result.data?.session?.user) {
    try {
      sessionStorage.setItem('supabase_user_cache', JSON.stringify(result.data.session.user));
    } catch (e) {}
  }

  return result.data;
}

export async function resendEmailOtp(email, userId = '') {
  if (!email || !email.includes('@')) throw new Error('Valid email address required.');
  return requestAuthEmailApi('/api/auth/resend', {
    email: email.trim(),
    userId: userId || undefined
  });
}

/** Check whether an email already has an account. Used only to give clear,
 * actionable sign-in and password-reset feedback in the auth UI. */
export async function checkEmailRegistered(email) {
  if (!email || !email.includes('@')) throw new Error('Valid email address required.');
  return requestAuthEmailApi('/api/auth/check-email', { email: email.trim() });
}

